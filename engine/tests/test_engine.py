# ---- regex / FSM -------------------------------------------------------------------------------
def test_regex_basics():
    d = compile_regex(r"SELECT (a|b)(, (a|b))*( LIMIT [1-9][0-9]{0,2})?")
    assert d.accepts("SELECT a")
    assert d.accepts("SELECT a, b, a LIMIT 250")
    assert not d.accepts("SELECT c")
    assert not d.accepts("SELECT a LIMIT 0")
    assert not d.accepts("SELECT a LIMIT 1000")


def test_token_fsm_masks_and_forced():
    d = compile_regex(r"SELECT x FROM (t1|t2)")
    vocab = ["SELECT", " x", " FROM", " t1", " t2", " zzz", "SEL", "ECT"]
    f = TokenFSM(d, vocab, eos_id=99)
    s = f.start
    assert set(f.allowed(s)) == {0, 6}                 # "SELECT" or the prefix piece "SEL"
    s = f.advance(s, 0)
    assert f.allowed(s) == [1] and f.forced_token(s) == 1
    s = f.advance(f.advance(s, 1), 2)
    assert set(f.allowed(s)) == {3, 4}
    s = f.advance(s, 3)
    assert f.allowed(s) == [99]                        # accepting: only EOS remains
    assert d.forced_text(d.run("SELECT x FROM ")) == "t"   # t1|t2 share the first char, then branch
    assert d.forced_text(d.run("SELECT x")) == " FROM t"


# ---- tokenizer parity ---------------------------------------------------------------------------
def test_tokenizer_stable_and_blocks():
    a = tk.encode("SELECT a.b FROM t\n  - name: x")
    assert a == tk.encode("SELECT a.b FROM t\n  - name: x")
    h = tk.hash_blocks(list(range(48)), 16)
    h2 = tk.hash_blocks(list(range(32)) + [999] * 16, 16)
    assert len(h) == 3 and h[:2] == h2[:2] and h[2] != h2[2]


