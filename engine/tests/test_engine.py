QUESTIONS = [
    ["What is total revenue by region?"],
    ["top 5 customers by revenue"],
    ["monthly revenue in 2023"],
    ["average order value by sales channel for EMEA"],
    ["how many completed orders by product category"],
    ["revenue by region", "now by segment"],
    ["units sold by category for Enterprise customers in 2024"],
    ["lowest 3 products by units sold"],
]


@pytest.mark.parametrize("qs", QUESTIONS)
def test_plan_is_grammatical_and_executes(qs):
    m = compile_model(YAML)
    plan = plan_sql(m, qs)
    assert m.accepts(plan.sql), plan.sql
    ex = SQLExecutor(seed_rows=2000)
    ex.ensure_tables(m)
    t = ex.execute(plan.sql)
    assert t.num_rows > 0, plan.sql


def test_followup_inherits_metric_and_filter():
    m = compile_model(YAML)
    p = plan_sql(m, ["total revenue in EMEA", "break that down by segment"])
    assert "SUM(orders.amount)" in p.sql and "customers.segment" in p.sql and "'EMEA'" in p.sql


def test_executor_rejects_writes_and_file_access():
    m = compile_model(YAML)
    ex = SQLExecutor(seed_rows=200)
    ex.ensure_tables(m)
    for bad in ("DROP TABLE orders", "SELECT 1; SELECT 2", "COPY orders TO 'x.csv'", "INSERT INTO orders VALUES (1)",
                "ATTACH 'x.db'", "PRAGMA database_list"):
        with pytest.raises(SQLValidationError):
            ex.execute(bad)
    with pytest.raises(SQLValidationError):
        ex.execute("SELECT * FROM read_csv('/etc/passwd')")
    assert ex.execute("SELECT COUNT(*) AS n FROM orders").to_pylist()[0]["n"] == 200


# ---- speculative decoding -----------------------------------------------------------------------
def test_speculation_is_lossless_and_effective():
    m = compile_model(YAML)
    base = NGramSQLDrafter()
    base.prime(tk.encode(m.raw), [v.sql for v in m.verified_queries])
    sql = plan_sql(m, ["top 5 customers by revenue"]).sql
    pieces = tk.pieces(sql)
    ids = [tk.piece_id(p) for p in pieces]
    steps, st = speculative_plan(ids, pieces, 1, NGramSQLDrafter(base=base), m.dfa)
    assert sum(e for e, _ in steps) == len(ids) - 1            # every token emitted exactly once
    assert st.tokens_per_step > 1.5, st
    assert 0 < st.acceptance_rate <= 1
    # without grammar jump-forward and corpus it still never changes the output, only the step count
    steps0, st0 = speculative_plan(ids, pieces, 1, NGramSQLDrafter(), None)
    assert sum(e for e, _ in steps0) == len(ids) - 1
    assert st.steps <= st0.steps


# ---- KV block manager ---------------------------------------------------------------------------
def test_kv_prefix_sharing_eviction_and_backpressure():
    kv = KVBlockManager(total_blocks=20, block_size=16)
    toks = list(range(16 * 8))
    h = tk.hash_blocks(toks, 16)
    a = kv.admit(h, len(toks), 16)
    assert a and not a.cached_blocks
    kv.commit_prefill(a)
    b = kv.admit(h, len(toks), 16)                       # shares the pinned prefix
    assert b and len(b.cached_blocks) == 8
    assert kv.admit(tk.hash_blocks(list(range(1000, 1000 + 16 * 12)), 16), 192, 16) is None   # no room: backpressure
    kv.release(a); kv.release(b)
    assert kv.stats()["idle_blocks"] == 8 and kv.private_total == 0
    other = tk.hash_blocks(list(range(5000, 5000 + 16 * 14)), 16)
    c = kv.admit(other, 16 * 14, 16)                     # forces LRU eviction of idle leaf blocks
    assert c and kv.evictions > 0
    assert len(kv.blocks) + kv.private_total <= 20


def test_latency_model_prefill_vs_decode():
    lm = LatencyModel("a100")
    cold = lm.step_time([(8000, 0)], [])
    warm = lm.step_time([(64, 7936)], [])                # 99% cached: only the tail is prefetched
    dec = lm.step_time([], [2000] * 64)
    assert cold > 5 * warm                               # prefix hit removes most of the prefill cost
    assert dec < cold / 5 and dec > lm.hw.overhead_ms / 1000   # decode is bandwidth-bound and cheap/step


# ---- full worker over HTTP ---------------------------------------------------------------------
def test_worker_sse_end_to_end(monkeypatch):
    monkeypatch.setenv("ARCTIC_FLIGHT", "0")
    monkeypatch.setenv("ARCTIC_SIM_TIME_SCALE", "0.05")
    from fastapi.testclient import TestClient
    import worker

    with TestClient(worker.app) as c:
        assert c.get("/healthz").json()["status"] == "ok"
        body = {"semantic_model": YAML, "messages": [{"role": "user", "content": "total revenue by region"}],
                "execute": True, "max_tokens": 128}
        evs = []
        for _ in range(2):
            evs = []
            with c.stream("POST", "/v1/generate", json=body) as r:
                for line in r.iter_lines():
                    if line.startswith("data:"):
                        evs.append(json.loads(line[5:]))
            types = [e["type"] for e in evs]
            assert types[0] == "start" and types[-1] == "done" and "token" in types
        done = evs[-1]
        assert done["result"]["rows"] == 4 and done["sql"].startswith("SELECT customers.region")
        assert evs[0]["cached_tokens"] > 0                      # 2nd identical prompt hits the prefix cache
        assert done["usage"]["spec_accepted"] > 0
        arrow = c.get(f"/v1/results/{done['result']['id']}")
        import pyarrow as pa
        assert pa.ipc.open_stream(arrow.content).read_all().num_rows == 4
        assert c.get("/stats").json()["completed"] == 2
        bad = c.post("/v1/generate", json={**body, "messages": [{"role": "user", "content": "zzz qqq"}]})
        assert '"type":"error"' in bad.text
