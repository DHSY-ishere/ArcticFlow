# ---- semantic compiler --------------------------------------------------------------------------
def test_compile_semantic_model():
    m = compile_model(YAML)
    assert set(m.tables) == {"orders", "customers", "products"}
    names = {x.name: x.expr for x in m.metrics}
    assert names["total_revenue"] == "SUM(orders.amount)"
    assert names["order_count"] == "COUNT(orders.order_id)"
    assert names["average_order_value"] == "AVG(orders.amount)"
    assert [t for _, t in m.join_path("customers", "products")] == ["orders", "products"]
    assert m.dfa.num_states >= 1
    sql = ("SELECT customers.region, SUM(orders.amount) AS total_revenue FROM orders JOIN customers ON "
           "orders.customer_id = customers.customer_id WHERE orders.status = 'completed' "
           "GROUP BY customers.region ORDER BY total_revenue DESC LIMIT 5")
    assert m.accepts(sql)
    for bad in ("SELECT * FROM orders", "SELECT customers.region FROM secrets",
                "DROP TABLE orders", sql + "; DROP TABLE orders",
                "SELECT SUM(orders.amount) AS x FROM orders JOIN customers ON orders.customer_id = customers.region"):
        assert not m.accepts(bad), bad


